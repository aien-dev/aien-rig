#!/usr/bin/env bash
# engine/ceiling.sh: the physical decode ceiling of each candidate model and format on an RTX 5070
# (12 GiB GDDR7, 672 GB/s nominal), and what fits in a 12 GiB budget. Every number is computed by
# aien-calc (exact arithmetic, stored receipt); this script only prints them into a Markdown table.
#
#   engine/ceiling.sh > engine/CEILING.md
#
# A dense model reads every weight once per generated token, plus the KV cache written so far.
# So tokens per second can never beat  bandwidth / (weight bytes + KV bytes read).
# Shapes come from each checkpoint's config.json (Qwen3-8B, Qwen3-4B-Instruct-2507, Qwen3-14B).
set -euo pipefail
IDS=()
command -v aien-calc >/dev/null || { echo "aien-calc not on PATH" >&2; exit 2; }

calc() { # calc EXPR -> sets V (value, 6 sig digits for ratios) and R (receipt id, short)
	local out
	out=$(aien-calc eval --precision 20 "$1")
	V=$(awk '/^decimal/{print $2}' <<<"$out")
	local full; full=$(awk '/^receipt/{print $2}' <<<"$out")
	R=${full:0:13}
	IDS+=("$full")
}

BW=672000000000          # RTX 5070 memory bandwidth, bytes/s (NVIDIA spec: 672 GB/s)
BUDGET=12884901888        # 12 GiB
SCRATCH=536870912         # 512 MiB allowance for activations, prefill rows, logits, kernel code
GB10_BW=273000000000      # DGX Spark GB10 nominal, bytes/s (for the GB10 rows of the receipts)

echo "# Decode ceiling on an RTX 5070 (12 GiB, 672 GB/s), per model and format"
echo
echo "Generated by \`engine/ceiling.sh\` on $(date -u +%Y-%m-%d). ON PAPER: arithmetic only, nothing here is measured."
echo "Every number has an aien-calc receipt (\`aien-calc verify <id>\` recomputes it; the full ids are in"
echo "\`engine/calc-receipts/\`)."
echo
echo "Rule: a dense model reads every weight once per generated token, plus the KV cache so far. Bytes per token"
echo "divided into 672 GB/s is a hard physical limit. Real kernels reach 70 to 80 percent of nominal bandwidth"
echo "(our FP8 GEMV measured 202 to 212 GB/s of the GB10's 273, about 77 percent; see the engine README)."
echo
echo "Budget: weights + KV cache + 512 MiB scratch must fit in 12 GiB (12,884,901,888 bytes). KV is bf16."
echo "MXFP4 = 4-bit e2m1 weights with one 8-bit scale per 32 weights = 17/32 byte per weight."
echo

row() { # name layer_weights head_weights layer_bytes_expr head_bytes_expr kv_per_token max_pos note
	local name=$1 lw=$2 hw=$3 lbe=$4 hbe=$5 kv=$6 maxpos=$7 note=$8
	calc "$lbe"; local lb=$V lbr=$R
	calc "$hbe"; local hb=$V hbr=$R
	calc "$lb + $hb"; local w=$V wr=$R
	calc "$BW / $w"; local c1=$V c1r=$R
	calc "$BW / ($w + $kv * 4096)"; local c4=$V c4r=$R
	calc "($BUDGET - $w - $SCRATCH) / $kv"; local fit=$V fitr=$R
	local fits ctx
	if [[ $fit == -* ]]; then fits="no"; ctx="0"; else
		ctx=${fit%%.*}; if (( ctx > maxpos )); then ctx="$maxpos (model max)"; fi
		if (( ${fit%%.*} >= 4096 )); then fits="yes"; else fits="no (under 4k context)"; fi
	fi
	printf -v c1 "%.1f" "$c1"; printf -v c4 "%.1f" "$c4"
	echo "| $name | $w ($wr) | $c1 ($c1r) | $c4 ($c4r) | $fits | $ctx ($fitr) | $note |"
}

echo "| model, format | bytes read per token, weights (receipt) | ceiling tok/s, short context | ceiling tok/s at 4k context | fits 12 GiB | most context that fits, tokens | note |"
echo "|---|---|---|---|---|---|---|"
# Qwen3-8B: 36 layers x 4096 x (q|k|v 6144 + o 4096 + gate|up 24576 + down 12288 columns), lm_head 151936 x 4096, untied.
L8="36*4096*(6144+4096+24576+12288)"; H8="151936*4096"
# FP8 block scales: per layer (48*32 + 32*32 + 192*32 + 32*96) bf16 words.
row "Qwen3-8B bf16" "$L8" "$H8" "2*$L8" "2*$H8" 147456 40960 "vendor weights; too big"
row "Qwen3-8B FP8 (Qwen's checkpoint), bf16 head" "$L8" "$H8" "$L8 + 36*2*(48*32+32*32+192*32+32*96)" "2*$H8" 147456 40960 "exact vendor file; runs on our engine today"
row "Qwen3-8B MXFP4 (from Qwen's FP8), bf16 head" "$L8" "$H8" "$L8*17/32" "2*$H8" 147456 40960 "omega W4 GEMV (cascade/w4-gemv); drift measured, see README"
row "Qwen3-8B MXFP4, MXFP4 head" "$L8" "$H8" "$L8*17/32" "$H8*17/32" 147456 40960 "head converter for bf16 not built yet"
# Qwen3-4B-Instruct-2507: hidden 2560, intermediate 9728, 36 layers, tied embedding (the lm_head is still read every token).
L4="36*2560*(6144+4096+19456+9728)"; H4="151936*2560"
row "Qwen3-4B-Instruct-2507 bf16" "$L4" "$H4" "2*$L4" "2*$H4" 147456 262144 "exact vendor file; runs on our engine today"
row "Qwen3-4B-Instruct-2507 MXFP4, bf16 head" "$L4" "$H4" "$L4*17/32" "2*$H4" 147456 262144 "needs a bf16 to MXFP4 converter (not built)"
# Qwen3-14B: hidden 5120, 40 layers, 40 q heads, 8 kv heads, intermediate 17408, untied (not on the Spark).
L14="40*5120*(7168+5120+34816+17408)"; H14="151936*5120"
row "Qwen3-14B FP8" "$L14" "$H14" "$L14 + 40*2*(56*40+40*40+272*40+40*136)" "2*$H14" 163840 40960 "too big"
row "Qwen3-14B MXFP4, bf16 head" "$L14" "$H14" "$L14*17/32" "2*$H14" 163840 40960 "checkpoint not downloaded; NOT MEASURED"
echo
echo "Not in the table: Qwen3-30B-A3B (MoE) reads only about 3B weights per token but holds 30.5B; at 4 bits that is"
echo "about 16 GB resident, so it does not fit 12 GiB without keeping experts in system RAM (PCIe, a different design)."
echo "Qwen3.8-27B at 4 bits is about 14 GB of weights: does not fit."
# Copy every receipt next to the table so `aien-calc verify` works from a clone.
if [[ -n ${CALC_EXPORT_DIR:-} ]]; then
	for id in "${IDS[@]}"; do aien-calc export "$id" "$CALC_EXPORT_DIR" >/dev/null; done
fi
